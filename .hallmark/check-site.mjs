import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {resolve} from 'node:path';
import {writeFileSync} from 'node:fs';
const require=createRequire(resolve(process.env.HALLMARK_PUPPETEER||'/tmp/undo-ui-check','check.js'));
const puppeteer=require('puppeteer-core');
const browser=await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const results=[];
const page=await browser.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const count=sel=>page.$$eval(sel,els=>els.length);
const text=sel=>page.$eval(sel,el=>el.textContent);
const click=async sel=>{console.log('Click',sel);await page.locator(sel).click()};
const check=(label,condition)=>{assert.ok(condition,label);results.push(label)};
try{
 await page.setViewport({width:1280,height:800});
 await page.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'reduce'}]);
 await page.goto(process.env.UNDO_TEST_URL||'http://127.0.0.1:3667/',{waitUntil:'networkidle2'});
 await page.evaluate(()=>document.fonts.ready);
 check('Four products render',await count('#productGrid .product')===4);
 const ids=await page.$$eval('section',els=>els.map(e=>e.id));
 check('All original sections preserved',ids.join('|')==='top|collection|why||story|policy|faq|');
 await click('[data-filter="cream"]');
 check('Colour filter narrows list',await count('#productGrid .product')===1&&(await text('#resultCount')).includes('1 sản phẩm'));
 await click('[data-filter="all"]');
 await click('#searchToggle');await page.type('#searchInput','not-a-mug');
 check('Search empty state',await count('#clearFilter')===1);
 await click('#clearFilter');check('Reset search restores all products',await count('#productGrid .product')===4);
 await page.type('#searchInput','sage');check('Search matches colour',await count('#productGrid .product')===1);
 await click('#closeSearch');await click('[data-fav="sage"]');await click('#wishlistToggle');
 check('Wishlist filter',await count('#productGrid .product')===1);
 await page.reload({waitUntil:'networkidle2'});
 check('Wishlist persists',await page.$eval('[data-fav="sage"]',el=>el.getAttribute('aria-pressed')==='true'));
 await click('#searchToggle');await page.type('#searchInput','onyx');
 // Search uses product name and tags, which include Midnight Black, not the data id.
 check('Unknown query has empty state',await count('#clearFilter')===1);
 await click('#clearFilter');await page.type('#searchInput','black');
 check('Search finds product by name',await count('#productGrid .product')===1);
 await click('#closeSearch');await click('.quick[data-view="onyx"]');
 check('Quick view opens',await page.$eval('#productModal',el=>el.getAttribute('aria-hidden')==='false'));
 await click('[data-color="blush"]');await click('#modalInc');await click('#modalAdd');
 check('Modal colour and quantity reach cart',(await text('#cartItems')).includes('Blush Pink')&&(await text('#cartCount'))==='2');
 check('Cart total correct',(await text('#cartFooter')).includes('498.000đ'));
 await page.keyboard.press('Escape');await page.reload({waitUntil:'networkidle2'});await click('#cartToggle');
 check('Cart persists after reload',(await text('#cartCount'))==='2');
 await click('[data-dec="blush"]');check('Decrease quantity recalculates total',(await text('#cartFooter')).includes('249.000đ'));
 await click('[data-inc="blush"]');await click('#checkoutBtn');
 check('Checkout carries total',(await text('#checkoutAmount'))==='498.000đ');
 await page.type('[name="name"]','Khách thử nghiệm');await page.type('[name="phone"]','0900000000');await page.type('[name="address"]','Địa chỉ mẫu');await page.type('[name="note"]','Kiểm tra giao diện');
 await click('#checkoutForm button[type="submit"]');
 check('Demo checkout completes and clears cart',(await text('#orderResult')).includes('498.000đ')&&(await text('#cartCount'))==='0');
 await click('#continueShop');await click('[data-add="cream"]');await click('#cartToggle');await click('[data-remove="cream"]');
 check('Remove item shows empty cart',(await text('#cartItems')).includes('Giỏ hàng đang trống'));
 await click('#shopAgain');
 await click('#faq summary');check('FAQ expands',await page.$eval('#faq details',el=>el.open));
 await page.type('#newsletterForm input','test@example.com');await click('#newsletterForm button');
 check('Newsletter demo reports no storage',(await text('#toast')).includes('email chưa được lưu'));
 for(const width of [320,375,768,1280,1440,1920]){
  await page.setViewport({width,height:900});await page.evaluate(()=>scrollTo(0,0));
  const metrics=await page.evaluate(()=>({width:innerWidth,doc:document.documentElement.scrollWidth,cta:document.querySelector('.actions').getBoundingClientRect().bottom,head:getComputedStyle(document.querySelector('h1')).fontFamily,container:document.querySelector('.wrap').getBoundingClientRect().width}));
  check(`No horizontal overflow at ${width}`,metrics.doc<=metrics.width);
  if(width===1280)check('Hero action above 800px fold',metrics.cta<800);
  if(width===1920)check('Container stays capped',metrics.container<=1440);
 }
 await page.setViewport({width:375,height:844});await click('#menuToggle');
 check('Mobile menu opens',await page.$eval('#menuToggle',el=>el.getAttribute('aria-expanded')==='true'));
 await click('#mobileMenu a[href="#collection"]');check('Mobile navigation closes menu',await page.$eval('#menuToggle',el=>el.getAttribute('aria-expanded')==='false'));
 await click('.quick[data-view="sage"]');await page.waitForFunction(()=>document.querySelector('#productModal').contains(document.activeElement));await page.keyboard.down('Shift');await page.keyboard.press('Tab');await page.keyboard.up('Shift');
 check('Dialog traps keyboard focus',await page.$eval('#productModal',el=>el.contains(document.activeElement)));
 await page.keyboard.press('Escape');check('Escape closes dialog',await page.$eval('#productModal',el=>el.inert));
 const nojs=await browser.newPage();await nojs.setJavaScriptEnabled(false);await nojs.goto('http://127.0.0.1:3667/',{waitUntil:'networkidle2'});
 check('Product content visible without JavaScript',await nojs.$$eval('#productGrid .product',els=>els.length)===4);await nojs.close();
 check('No JavaScript exceptions',errors.length===0);
 console.log(JSON.stringify({passed:results.length,checks:results,errors},null,2));
 writeFileSync('.hallmark/feature-checks.json',JSON.stringify({passed:results.length,checks:results,errors},null,2));
}catch(error){console.log(await page.evaluate(()=>({url:location.href,formHidden:document.querySelector('#checkoutForm').hidden,modal:document.querySelector('#checkoutModal').outerHTML,active:document.activeElement?.outerHTML,errors:document.querySelector('#orderResult').textContent})));await page.screenshot({path:'.hallmark/check-failure.png'});throw error}finally{await browser.close()}
